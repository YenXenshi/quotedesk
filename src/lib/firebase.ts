// Subscribe to quotes for the current signed-in owner only
export function subscribeToOwnerQuotes(
  ownerId: string,
  onQuotesReceived: (quotes: Quote[]) => void,
  onError: (error: Error) => void
): () => void {
  const quotesCol = collection(db, 'quotes');
  // Secure query matching security rule: ownerId == request.auth.uid
  const q = query(
    quotesCol,
    where('ownerId', '==', ownerId),
    orderBy('createdAt', 'desc')
  );

  const unsubscribe = onSnapshot(
    q,
    (snapshot) => {
      const quotes: Quote[] = snapshot.docs.map((docSnap) => {
        const data = docSnap.data();
        return {
          id: docSnap.id,
          ...data,
          createdAt: data.createdAt?.toDate ? data.createdAt.toDate() : data.createdAt,
          updatedAt: data.updatedAt?.toDate ? data.updatedAt.toDate() : data.updatedAt,
        } as Quote;
      });
      onQuotesReceived(quotes);
    },
    (err) => {
      try {
        handleFirestoreError(err, OperationType.LIST, 'quotes');
      } catch (wrapped) {
        onError(wrapped as Error);
      }
    }
  );

  return unsubscribe;
}
