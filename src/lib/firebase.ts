// Sign in with Google Popup
export async function signInWithGoogle(): Promise<User> {
  try {
    const result = await signInWithPopup(auth, googleProvider);
    return result.user;
  } catch (err) {
    console.error('Sign in error:', err);
    throw err;
  }
}

// Sign Out
export async function logOut(): Promise<void> {
  await firebaseSignOut(auth);
}

// Save a new quote with a unique ID generated by Firestore database (never a counted number)
export async function saveQuoteToFirestore(
  quoteData: Omit<Quote, 'id' | 'createdAt' | 'updatedAt' | 'ownerId'>
): Promise<Quote> {
  if (!auth.currentUser) {
    throw new Error('You must be signed in to save a quote.');
  }

  const quotesCol = collection(db, 'quotes');
  // Generate unique ID directly from Firestore database
  const newQuoteRef = doc(quotesCol);
  const quoteId = newQuoteRef.id;

  const quotePayload = {
    ...quoteData,
    clientNotes: quoteData.clientNotes || '',
    draftMessage: quoteData.draftMessage || '',
    id: quoteId,
    ownerId: auth.currentUser.uid,
    ownerEmail: auth.currentUser.email || '',
    createdAt: serverTimestamp(),
    updatedAt: serverTimestamp(),
  };

  try {
    await setDoc(newQuoteRef, quotePayload);
    return {
      ...quotePayload,
      createdAt: new Date(),
      updatedAt: new Date(),
    } as Quote;
  } catch (error) {
    handleFirestoreError(error, OperationType.CREATE, `quotes/${quoteId}`);
  }
}

// Update a quote's status (Accepted or Declined or Sent)
export async function updateQuoteStatusInFirestore(
  quoteId: string,
  newStatus: Quote['status']
): Promise<void> {
  if (!auth.currentUser) {
    throw new Error('You must be signed in to update a quote.');
  }

  const docRef = doc(db, 'quotes', quoteId);
  try {
    await updateDoc(docRef, {
      status: newStatus,
      updatedAt: serverTimestamp(),
    });
  } catch (error) {
    handleFirestoreError(error, OperationType.UPDATE, `quotes/${quoteId}`);
  }
}

